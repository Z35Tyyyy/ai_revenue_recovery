#!/usr/bin/env python3
"""Evaluate the engine vs. baselines on a fresh, unseen holdout population.

Writes:
    reports/eval.json     full machine-readable results (used by the dashboard)
    docs/RESULTS.md       a human-readable, auto-generated results summary

The holdout uses a different seed from training, so the models are scored on
customers and failures they have never seen.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from rich.console import Console
from rich.table import Table

from recovery.config import get_settings
from recovery.domain.models import format_inr
from recovery.eval.harness import evaluate
from recovery.ml.models import RecoveryModel, TimingModel
from recovery.simulation.generator import generate_population

console = Console()


def _fmt_days(d):
    return f"{d:.1f}" if d is not None else "—"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--customers", type=int, default=6000)
    p.add_argument("--failures", type=int, default=9000)
    p.add_argument("--holdout-seed", type=int, default=9999)
    args = p.parse_args()

    settings = get_settings()
    settings.ensure_dirs()

    console.rule("[bold]AI Revenue Recovery · held-out evaluation")
    rm = RecoveryModel.load(settings.model_dir)
    tm = TimingModel.load(settings.model_dir)

    console.print(
        f"Holdout (unseen): [cyan]{args.customers}[/] customers · "
        f"[cyan]{args.failures}[/] failed charges · seed=[cyan]{args.holdout_seed}[/]"
    )
    holdout = generate_population(
        n_customers=args.customers, n_failures=args.failures, seed=args.holdout_seed
    )
    result = evaluate(holdout, rm, tm)

    # --- console table ---
    table = Table(title="Recovery performance on held-out failures", show_lines=False)
    table.add_column("policy", style="cyan")
    table.add_column("recovery rate", justify="right")
    table.add_column("revenue recovered", justify="right", style="green")
    table.add_column("₹-recovery rate", justify="right")
    table.add_column("retries", justify="right")
    table.add_column("messages", justify="right")
    table.add_column("avg days", justify="right")
    order = ["no_action", "fixed_retry", "generic_dunning", "engine"]
    for name in order:
        m = result.policies[name]
        style = "bold green" if name == "engine" else None
        table.add_row(
            name,
            f"{m.recovery_rate:.1%}",
            format_inr(m.revenue_recovered_paise),
            f"{m.revenue_recovery_rate:.1%}",
            f"{m.retries:,}",
            f"{m.nudges:,}",
            _fmt_days(m.avg_days_to_recover),
            style=style,
        )
    console.print(table)

    up_fixed = result.uplift_vs("fixed_retry", "engine")
    up_generic = result.uplift_vs("generic_dunning", "engine")
    console.print(
        f"[bold]Engine uplift[/] vs fixed-retry: "
        f"[green]+{up_fixed['recovery_rate_abs'] * 100:.1f} pts "
        f"({up_fixed['recovery_rate_rel'] * 100:.0f}% relative)[/], "
        f"+{format_inr(up_fixed['revenue_recovered_delta_paise'])} recovered"
    )
    console.print(
        f"[bold]Engine uplift[/] vs generic-dunning: "
        f"[green]+{up_generic['recovery_rate_abs'] * 100:.1f} pts "
        f"({up_generic['recovery_rate_rel'] * 100:.0f}% relative)[/]"
    )
    console.print(f"Triage prediction AUC (held-out): [cyan]{result.engine_prediction_auc:.3f}[/]")

    # --- persist ---
    payload = result.as_dict()
    payload["holdout"] = {
        "customers": args.customers,
        "failures": args.failures,
        "seed": args.holdout_seed,
    }
    payload["uplift"] = {"vs_fixed_retry": up_fixed, "vs_generic_dunning": up_generic}
    eval_path = settings.report_dir / "eval.json"
    eval_path.write_text(json.dumps(payload, indent=2))
    console.print(f"  ✓ results → [green]{eval_path}[/]")

    _write_results_md(result, up_fixed, up_generic, args, Path("docs/RESULTS.md"))
    console.print("  ✓ summary → [green]docs/RESULTS.md[/]")
    console.rule("[green]done")


def _write_results_md(result, up_fixed, up_generic, args, path: Path) -> None:
    order = ["no_action", "fixed_retry", "generic_dunning", "engine"]
    labels = {
        "no_action": "No recovery (floor)",
        "fixed_retry": "Fixed next-day retry (Razorpay default)",
        "generic_dunning": "Fixed retry + generic email",
        "engine": "**AI Revenue Recovery engine**",
    }
    lines = [
        "# Results",
        "",
        "> Auto-generated by `make eval` (`scripts/run_eval.py`). Reproducible: the "
        f"holdout uses seed `{args.holdout_seed}`, unseen during training.",
        "",
        f"Evaluated on a held-out population of **{args.customers:,} customers** and "
        f"**{args.failures:,} failed recurring charges**, all policies facing the "
        "identical hidden ground truth.",
        "",
        "## Headline",
        "",
        f"- **Recovery rate: {result.policies['engine'].recovery_rate:.1%}** "
        f"vs {result.policies['fixed_retry'].recovery_rate:.1%} for the fixed-retry "
        f"default — **+{up_fixed['recovery_rate_abs'] * 100:.1f} points "
        f"({up_fixed['recovery_rate_rel'] * 100:.0f}% relative)**.",
        f"- **+{format_inr(up_fixed['revenue_recovered_delta_paise'])}** additional "
        "revenue recovered on the holdout vs fixed retry.",
        f"- Achieved with **{result.policies['engine'].retries:,} retries** vs "
        f"{result.policies['fixed_retry'].retries:,} for fixed retry — higher recovery, "
        "fewer bank attempts (it waits for the right moment instead of hammering).",
        f"- Held-out triage AUC: **{result.engine_prediction_auc:.3f}**.",
        "",
        "## Full comparison",
        "",
        "| Policy | Recovery rate | Revenue recovered | ₹-rate | Retries | Msgs | Days |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in order:
        m = result.policies[name]
        days = f"{m.avg_days_to_recover:.1f}" if m.avg_days_to_recover is not None else "—"
        lines.append(
            f"| {labels[name]} | {m.recovery_rate:.1%} | "
            f"{format_inr(m.revenue_recovered_paise)} | {m.revenue_recovery_rate:.1%} | "
            f"{m.retries:,} | {m.nudges:,} | {days} |"
        )
    lines += [
        "",
        "## Recovery rate by failure class (engine)",
        "",
        "| Failure class | Fixed retry | Engine |",
        "|---|---|---|",
    ]
    eng_by = result.policies["engine"].by_class_rate()
    fix_by = result.policies["fixed_retry"].by_class_rate()
    for cls in sorted(eng_by):
        lines.append(f"| {cls} | {fix_by.get(cls, 0):.1%} | {eng_by[cls]:.1%} |")
    lines += [
        "",
        "## What the bandit learned",
        "",
        "Success rate the contextual bandit converged to per (failure class → action):",
        "",
        "```json",
        json.dumps(result.bandit, indent=2),
        "```",
        "",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
